"""Prepared conversation branches grounded in the session's reviewed case.

Routing is contextual but never approves terms, changes money or adds evidence.
The free-text demo remains a rule-based simulator, not a generative model.
"""

from .dialogue import dialogue_topic


def last_topic(session):
    """Topic of the latest chat utterance; never inherit from a prior proposal."""
    message = next((message for message in reversed(session.get("messages", []))
                    if message.get("role") == "user"), None)
    if not message or message.get("kind", "message") != "message":
        return None
    return dialogue_topic(message["text"], has_discovered=bool(session.get("discovered_interests")))


def _money(value):
    return f"{value:,}".replace(",", " ") + " ₽"


def _known(session, was_discovered):
    return was_discovered or bool(session.get("discovered_interests"))


def fallback_reply(session):
    """Name concrete exits from a failed match and acknowledge the limit honestly."""
    unsure = "Не уверена, что верно поняла эту реплику. " if session["scenario"]["id"] == "scope" else "Не уверен, что верно понял эту реплику. "
    if session.get("proposal") and session["proposal"]["client_status"] == "accepted":
        return (unsure + "Последний пакет по-прежнему принят. "
                "Хотите сверить его состав, оплату или обсудить другой вариант?")
    if session.get("proposal"):
        return (unsure + "Можно разобрать причину моей реакции, "
                "сравнить другой пакет или подвести итог. Например: «Что в моём предложении вам не подходит?»")
    if session["scenario"]["id"] == "scope":
        return (unsure + "Давайте выберем один вопрос: "
                "что нужно к сдаче, какие задачи менять или как обосновать срок. Можно коротко: «Про сроки».")
    return (unsure + "Обсудим общую цену, первый платёж или состав работ. "
            "Можно коротко: «Про бюджет» или спросить: «Что стоит за вашей просьбой?»")


def proposal_reason(session, interest, was_discovered):
    """Explain an old pre-discovery refusal without asking an answered question.

    Its status is still rejected. Learning the priority never retroactively
    approves a package; a fresh structured proposal is required.
    """
    proposal = session.get("proposal")
    if not proposal:
        return ""
    reason = proposal["reason"]
    if (proposal["client_status"] == "rejected" and _known(session, was_discovered)
            and "сначала выясните его приоритет" in reason):
        return ("При отправке пакета мы ещё не обсудили мой приоритет. Теперь он понятен: " + interest
                + " Тот пакет остаётся отклонённым; после обсуждения его можно отправить повторно или выбрать другой.")
    return reason


def topic_reply(session, topic, interest, was_discovered):
    """Specific answers before/after discovery, derived solely from fixed case facts."""
    scenario = session["scenario"]
    baseline = scenario["baseline"]
    priority = session["priority"]
    known = _known(session, was_discovered)
    proposal = session.get("proposal")
    is_scope = scenario["id"] == "scope"
    if topic == "summary":
        if proposal:
            return None  # The caller renders the authoritative proposal status.
        if known:
            return "Зафиксируем, что уже выяснили: " + interest + " Пакет ещё не предложен. Какие цену, объём и срок вы предлагаете связать между собой?"
        return (f"Пока есть исходные условия: {_money(baseline['price'])}, {baseline['hours']} часов, "
                f"{baseline['deadline_days']} рабочих дней. Остаётся моя просьба изменить проект. На чём сосредоточимся: "
                + ("что важнее сохранить — дату или полный объём?" if is_scope else "дело в общей цене или в первом платеже?"))
    if topic == "next_step":
        if proposal and proposal["client_status"] == "accepted":
            return "Следующий шаг — проверить обязательства по принятому пакету. Если готовы их взять, подтвердите договорённость в карточке условий; можно также продолжить обсуждение."
        if proposal:
            return "Сначала разберём, почему пакет не подошёл: " + proposal_reason(session, interest, was_discovered) + " Какое условие вы готовы изменить в следующем варианте?"
        if known:
            return "Теперь сопоставим мой приоритет с возможностями вашей команды. Можно обсудить уступку, обосновать ограничения или открыть карточку условий и предложить пакет."
        return "Давайте определимся, что обсуждаем первым: причину моей просьбы или ограничения вашей команды? Затем можно сопоставить варианты по сроку, объёму и цене."
    if topic == "reason":
        if proposal and proposal["client_status"] == "rejected":
            return "В вашем пакете меня не устраивает следующее: " + proposal_reason(session, interest, was_discovered) + " Обсудим, какое условие можно изменить, не добавляя невыполнимых обещаний?"
        if proposal and proposal["client_status"] == "accepted":
            return "Пакет соответствует моему ограничению: " + proposal["reason"] + " С вашей стороны ещё важно проверить срок и экономику; моё согласие само по себе этого не гарантирует."
        if known:
            return "За моей просьбой стоит такое ограничение: " + interest + " Как бы вы учли его, сохранив выполнимость проекта?"
        return "Вы хотите понять причину моей просьбы или обсудить, почему исходный запрос не подходит вашей команде?"
    if topic == "goal":
        if known:
            return "Результат для меня важнее формулировки уступки: " + interest + " Какая часть вашего решения сохранит этот результат?"
        return ("Сейчас обсуждаем исходный проект и дополнительные 40 часов задач. Мне нужен понятный результат. Вы хотите поговорить о составе работ или о дате, к которой он будет готов?"
                if is_scope else "Хочу обсудить проект, на который исходно запланировано 120 часов. В моём запросе есть и результат, и денежные условия. Что вы предлагаете обсудить первым: состав работ, общую цену или платёж при старте?")
    if topic == "deadline":
        if not known:
            return (f"В исходном плане {baseline['deadline_days']} рабочих дней и {baseline['hours']} часов при ресурсе 8 часов в день. "
                    + ("С дополнительными задачами объём станет 160 часов. Вы хотите обсудить перенос или состав работ к прежней дате?"
                       if is_scope else "Моя просьба касается денег. Вы предлагаете изменить срок вместе с ценой или оставить исходную дату?"))
        if priority == "deadline":
            return ("Дату сдвигать нельзя. "
                    + "Для неё можно заменить 20 часов прежних работ на 20 часов приоритетных новых. Остальные новые задачи не обещаем. Как вы объясните команде и мне эту замену?")
        if priority == "full_scope":
            return "Перенос на 5 рабочих дней допустим: полный объём — 160 часов, срок — 20 рабочих дней. Какие цену и состав работ вы зафиксируете вместе с новой датой?"
        return "В этом кейсе обсуждаем исходные 15 рабочих дней. Моя просьба связана с деньгами: " + interest + " Какой пакет решит это без лишнего обещания по срокам?"
    if topic == "scope":
        if not known:
            return ("Исходно 120 часов, дополнительно прошу ещё 40. Вы рассматриваете весь объём или предлагаете заменить часть прежних задач новыми?"
                    if is_scope else "В исходном пакете 120 часов. Есть и самостоятельный вариант на 80 часов, в котором остальные работы исключены. Вы хотите обсудить сокращённый результат или способ сохранить весь объём?")
        return {
            "deadline": "Для даты нужны 20 часов новых задач. Можно убрать 20 часов прежних: получится 100 часов исходных и 20 новых. Оставшиеся новые задачи сейчас не обязательны и не становятся обещанием на потом. Как вы сформулируете границы этого пакета?",
            "full_scope": "Нужны все 120 часов исходных и все 40 часов новых работ. Исключать часть не подходит; можно обсуждать дату и цену. Что вы готовы изменить при сохранении всех 160 часов?",
            "budget": "Самостоятельный пакет на 80 часов подходит. Остальные 40 часов нужно явно исключить, без обещания выполнить бесплатно позже. Как вы объясните ценность сокращённого результата?",
            "cashflow": "Нужны все 120 часов. Сокращение объёма мою проблему не решает — обсуждать стоит сумму первого платежа. Какой график вы можете предложить при сохранении полной цены?",
        }[priority]
    if topic == "budget":
        if not known:
            return ("Исходная цена — 200 000 ₽. Если сумма изменится, хочу понимать, что получу взамен: весь набор задач, прежнюю дату или другой состав работ. О каком варианте вы говорите?"
                    if is_scope else "Исходная цена — 180 000 ₽, мой запрос — 120 000 ₽. Вы хотите обсудить всю сумму проекта или отдельно первый платёж?")
        return {
            "deadline": "Главное ограничение — дата, а не доплата. При замене задач сохраняются исходные 200 000 ₽ и 120 часов. Предложение сделать все 160 часов в прежний срок не создаст дополнительный ресурс команды.",
            "full_scope": "Для полного объёма допустима цена до 240 000 ₽ при явно зафиксированных 160 часах и переносе на 5 рабочих дней. Как вы обоснуете цену, чтобы было понятно, за какой результат я плачу?",
            "budget": "120 000 ₽ — предел всего проекта. Рассрочка не увеличит бюджет. Можно сократить пакет до 80 часов; как вы свяжете меньшую цену с меньшим объёмом?",
            "cashflow": "Полная цена 180 000 ₽ допустима. Снижать её ради моего ограничения необязательно: на старте есть максимум 60 000 ₽. Обсудим, как распределить оплату?",
        }[priority]
    if topic == "payment":
        if not known:
            return (f"Исходный график: {baseline['payment']}. "
                    + ("Мне важно видеть, какой объём и срок стоят за графиком платежей. Какие изменения вы рассматриваете вместе с оплатой?"
                       if is_scope else "Вы предлагаете изменить сумму первого платежа при сохранении цены или снизить общую стоимость проекта?"))
        if priority == "cashflow":
            return "При старте доступно не больше 60 000 ₽; остаток — после сдачи. Пакет с авансом 30% предусматривает 54 000 ₽ сейчас и 126 000 ₽ после сдачи. Полная цена остаётся 180 000 ₽. Какие обязательства вы зафиксируете вместе с этим графиком?"
        if priority == "budget":
            return "Проблема во всей сумме: больше 120 000 ₽ на проект нет. Разбивка 180 000 ₽ на платежи этого не изменит. Обсудим сокращение объёма вместо рассрочки?"
        return "График остаётся 50% при старте и 50% после сдачи. Для меня сейчас важнее договориться об объёме и дате. Какой вариант вы рассматриваете?"
    if topic == "compromise":
        if not known:
            return ("Обмен уступками возможен. Что вы можете предложить со своей стороны: "
                    + ("другой состав задач, перенос срока или изменение цены?"
                       if is_scope else "другой объём за меньшую цену или изменение первого платежа?"))
        return {
            "deadline": "Моя уступка — исключить 20 часов прежних задач и не требовать оставшиеся новые. Взамен сохраняем дату и включаем 20 часов приоритетных новых задач. Какую формулировку пакета вы предложите?",
            "full_scope": "Со своей стороны могу обсуждать перенос на 5 рабочих дней и бюджет до 240 000 ₽. Взамен нужен весь объём. Какой из полных пакетов выполним для вашей команды: с прежней ценой или с доплатой?",
            "budget": "Со своей стороны готов отказаться от 40 часов работ. Взамен нужен самостоятельный результат за 120 000 ₽. Как вы обозначите, что исключённые задачи не переходят в бесплатный следующий этап?",
            "cashflow": "Полную цену 180 000 ₽ сохраняем, но аванс должен быть не больше 60 000 ₽. Остаток оплачиваем после сдачи. Какой график вы готовы оформить при сохранении всех 120 часов?",
        }[priority]
    if topic == "risk":
        if proposal:
            terms = proposal["terms"]
            return (f"В последнем пакете {terms['hours']} часов, {terms['deadline_days']} рабочих дней и {_money(terms['price'])}. "
                    "Не хочу договориться на бумаге и потом столкнуться с задержкой или невыполненными работами. Как вы обоснуете, что вашей команде хватает ресурса на этот пакет?")
        return ("Для меня важно, чтобы обещание было выполнимо. При ресурсе 8 часов в день цена сама по себе не увеличивает мощность команды. "
                + ("Если сохраняем срок, нужно обсуждать объём; если сохраняем все задачи — срок и цену."
                   if is_scope else "Если снижаем цену, нужно проверить затраты и объём; если меняем аванс, общая цена остаётся прежней."))
    return None


def argument_reply(session, topic, interest, was_discovered):
    """React to an argument without pretending to accept a described package."""
    if not _known(session, was_discovered):
        return "Понимаю, что условия связаны с ресурсами вашей команды. Мне нужно понять, что получится в результате: какой объём вы готовы сделать, в какой срок и при какой цене?"
    return {
        "deadline": "Связь между объёмом и датой понятна. В замене для меня важны границы: 20 часов прежних задач убираем, а из новых берём только 20 приоритетных. Как зафиксируем, что остальное не обещано на бесплатный следующий этап?",
        "full_scope": "Довод о ресурсе команды понятен. Мне нужны все 160 часов работ; ради этого допустимы 20 рабочих дней и цена до 240 000 ₽. Какую точную цену вы предлагаете за полный состав работ с новой датой?",
        "budget": "Понимаю связь цены и затрат. Для меня ключевое — самостоятельный результат: если берём 80 часов за 120 000 ₽, он должен работать без обязательной покупки остальных задач. Как обозначим состав и границы этого результата?",
        "cashflow": "Понимаю, что другой график позволяет сохранить цену. Мне нужны все 120 часов, а на старте доступно не больше 60 000 ₽. Какой конкретно аванс и какой остаток после сдачи вы предлагаете за полные 180 000 ₽?",
    }[session["priority"]]
